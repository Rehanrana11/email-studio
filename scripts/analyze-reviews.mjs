#!/usr/bin/env node
// Analyse notes/reviews.jsonl and write notes/reviews-scratchpad.md.
// Every number in the scratchpad comes from this script, so the analysis is reproducible, not hand-typed.
//
//   node scripts/analyze-reviews.mjs

import { readFileSync, writeFileSync } from "node:fs";

const rows = readFileSync("notes/reviews.jsonl", "utf8").trim().split("\n").map((l) => JSON.parse(l));
const n = rows.length;
const mean = (xs) => xs.reduce((a, b) => a + b, 0) / (xs.length || 1);
const sd = (xs) => {
  const m = mean(xs);
  return Math.sqrt(xs.reduce((a, x) => a + (x - m) ** 2, 0) / Math.max(1, xs.length - 1));
};
// 95% CI for a mean using the normal approximation (fine at n >= 30; flagged below when n is small)
const ci = (xs) => {
  const half = 1.96 * (sd(xs) / Math.sqrt(xs.length || 1));
  return [mean(xs) - half, mean(xs) + half];
};
const f2 = (x) => x.toFixed(2);
const countBy = (xs, key) => xs.reduce((m, r) => m.set(r[key], (m.get(r[key]) || 0) + 1), new Map());

const stars = rows.map((r) => r.stars);
const [lo, hi] = ci(stars);
const positive = rows.filter((r) => r.stars >= 4);
const negative = rows.filter((r) => r.stars <= 2);

let md = `# Spice Circle: reviews scratchpad

Generated by \`scripts/analyze-reviews.mjs\` from \`notes/reviews.jsonl\` (${n} **fake** reviews from \`scripts/gen-reviews.mjs\`).
Practice data only. Never quote these as real customer reviews.

## Overall
| Metric | Value |
|---|---|
| Reviews | ${n} |
| Mean stars | ${f2(mean(stars))} (95% CI ${f2(lo)}–${f2(hi)}) |
| Positive (4–5★) | ${positive.length} (${((positive.length / n) * 100).toFixed(0)}%) |
| Negative (1–2★) | ${negative.length} (${((negative.length / n) * 100).toFixed(0)}%) |

### Star distribution
| Stars | Count |
|---|---|
${[5, 4, 3, 2, 1].map((s) => `| ${s}★ | ${rows.filter((r) => r.stars === s).length} |`).join("\n")}

## By group
| Group | Reviews | Mean stars | 95% CI | % negative |
|---|---|---|---|---|
`;
for (const [group] of [...countBy(rows, "group")].sort()) {
  const g = rows.filter((r) => r.group === group);
  const gs = g.map((r) => r.stars);
  const [glo, ghi] = ci(gs);
  md += `| ${group} | ${g.length} | ${f2(mean(gs))} | ${f2(glo)}–${f2(ghi)}${g.length < 30 ? " (small n)" : ""} | ${((g.filter((r) => r.stars <= 2).length / g.length) * 100).toFixed(0)}% |\n`;
}
md += `
Overlapping intervals mean a gap between groups may be noise. Don't act on a group difference unless the
intervals separate or you have more data.

## What negative reviews are about (1–2★, n=${negative.length})
| Theme | Count | Example |
|---|---|---|
`;
for (const [theme, count] of [...countBy(negative, "theme")].sort((a, b) => b[1] - a[1])) {
  const ex = negative.find((r) => r.theme === theme);
  md += `| ${theme} | ${count} | "${ex.text}" (${ex.id}) |\n`;
}
md += `
## What positive reviews are about (4–5★, n=${positive.length})
| Theme | Count | Example |
|---|---|---|
`;
for (const [theme, count] of [...countBy(positive, "theme")].sort((a, b) => b[1] - a[1])) {
  const ex = positive.find((r) => r.theme === theme);
  md += `| ${theme} | ${count} | "${ex.text}" (${ex.id}) |\n`;
}
md += `
## By blend
| Blend | Reviews | Mean stars | Negative |
|---|---|---|---|
`;
for (const [blend] of [...countBy(rows, "blend")].sort()) {
  const b = rows.filter((r) => r.blend === blend);
  md += `| ${blend} | ${b.length} | ${f2(mean(b.map((r) => r.stars)))} | ${b.filter((r) => r.stars <= 2).length} |\n`;
}
const opsNeg = negative.filter((r) => ["shipping", "billing", "wrong-item"].includes(r.theme)).length;
md += `
## Read-out
- ${opsNeg} of ${negative.length} negative reviews are about operations (shipping, billing, wrong items), not flavour.
  The fix is fulfilment and billing, not the blends.
- Recipe cards come up again and again in positive reviews: keep them prominent in emails 01–02.
- Themes come from a fixed label in the generator. With real reviews you'd code themes by hand on a sample
  first (open coding), then check an LLM labeller against your codes before trusting it at scale.
`;
writeFileSync("notes/reviews-scratchpad.md", md);
console.log(`Wrote notes/reviews-scratchpad.md (${n} reviews, mean ${f2(mean(stars))}).`);
